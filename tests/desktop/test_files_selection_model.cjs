const assert=require('node:assert/strict'),fs=require('fs'),vm=require('vm');
const context={Identity:require('../../res/lumen-desktop/shell/FileIdentity.js'),module:{exports:{}}};
vm.runInNewContext(fs.readFileSync('res/lumen-desktop/shell/FilesSelectionModel.js','utf8').replace(/^\.import.*$/m,''),context);
const s={};for(const [name,fn] of Object.entries(context.module.exports))s[name]=(...args)=>JSON.parse(JSON.stringify(fn(...args)));
const row=(path,inode)=>({path,identity:{device:'1152921504606846977',inode:String(inode)},renameFollow:true});
const rows=[row('/one','1152921504606846978'),row('/two','1152921504606846979'),row('/three','1152921504606846980')];
const initial=s.capture(rows,['/one'],1,2);
assert.deepEqual(s.reconcile(rows,initial),{paths:['/one'],current:1,anchor:2},'Unselected focused object stays focused');
assert.deepEqual(s.reconcile([rows[2],rows[0],rows[1]],initial),{paths:['/one'],current:2,anchor:0},'Resort preserves exact independent roles');
assert.deepEqual(s.reconcile([rows[0],row('/two',99),rows[2]],initial),{paths:['/one'],current:-1,anchor:2},'Replacement cannot inherit focused object');
const transaction=s.begin(rows,['/one'],1,2,'folder:grid:output1','replace');
assert.deepEqual(s.finish(transaction,rows,'folder:grid:output1',[rows[2]]),{paths:['/three'],current:1,anchor:2});
assert.deepEqual(initial.selection,[s.ref(rows[0])],'Band preview must not mutate the original set');
assert.deepEqual(s.combine(initial,[rows[0],rows[1]],'toggle').selection,[s.ref(rows[1])]);
assert.deepEqual(s.combine(initial,[rows[0],rows[1]],'add').selection,[s.ref(rows[0]),s.ref(rows[1])]);
assert.equal(s.finish(transaction,rows,'other:grid:output1',[rows[2]]),null,'Different folder/output/view cannot receive release');
assert.equal(s.finish(transaction,[rows[1],rows[0],rows[2]],transaction.context,[rows[2]]),null,'Resort cancels a captured geometry transaction');
assert.equal(s.finish(transaction,[rows[0],row('/two',99),rows[2]],transaction.context,[rows[2]]),null,'Replacement cancels band');
assert.equal(s.begin([{path:'/unknown'}],[],0,0,'folder','replace'),null,'Missing identity fails closed');
assert.equal(s.ref({path:'/unsafe',identity:{device:1,inode:2**60}}),null,'Already rounded identity fails closed');
const rect=s.rectangle({x:40,y:50},{x:10,y:5});assert.deepEqual(rect,{x:10,y:5,width:30,height:45});
const boxes=[{row:rows[0],x:0,y:0,width:15,height:15},{row:rows[1],x:20,y:20,width:20,height:20},{row:rows[2],x:40,y:0,width:20,height:30}];
assert.deepEqual(s.hits(rect,boxes),[s.ref(rows[0]),s.ref(rows[1])],'Only positive intersection selects rows');
assert.deepEqual(s.hits(s.rectangle({x:10,y:10},{x:10,y:10}),boxes),[],'Click is not a selection rectangle');
assert.equal(s.rectangle({x:Infinity,y:0},{x:1,y:1}),null);
assert.equal(s.rectangle({x:0,y:0},{x:NaN,y:1}),null);
const renamed=[row('/renamed',rows[0].identity.inode),rows[1],rows[2]];assert.deepEqual(s.reconcile(renamed,initial).paths,['/renamed']);
assert.deepEqual(s.reconcile([row('/a',rows[0].identity.inode),row('/b',rows[0].identity.inode)],initial).paths,[],'Ambiguous hard links are never guessed');
console.log('PASS exact band selection policy, distinct focus/anchor, revision cancellation and geometry');

const linked={...rows[0],renameFollow:false};
assert.deepEqual(s.reconcile([row("/remaining",linked.identity.inode)],{selection:[linked]}).paths,[]);
assert.deepEqual(s.reconcile([rows[0]],{selection:[{path:"/missing",identity:rows[0].identity}]}).paths,[]);
assert.deepEqual(s.reconcile([linked],{selection:[linked]}).paths,[linked.path]);
assert.deepEqual(s.combine(initial,[rows[0],rows[0]],"toggle").selection,[],"Duplicate hit boxes toggle once only");

assert.equal(s.contains(boxes[0],{x:14.9,y:14.9}),true);
assert.equal(s.contains(boxes[0],{x:15,y:5}),false,"Actual delegate edge leaves explicit blank gutter");
assert.equal(s.contains(boxes[0],{x:Infinity,y:5}),false);
