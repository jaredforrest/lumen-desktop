const fs=require('fs'),vm=require('vm'),assert=require('assert');
const model=vm.createContext({});vm.runInContext(fs.readFileSync('res/lumen-desktop/shell/ScrollGeometry.js','utf8'),model);
const reveal=(...args)=>vm.runInContext('reveal('+args.join(',')+')',model);
assert.equal(reveal(0,200,600,250,40),98);
assert.equal(reveal(100,200,600,20,40),12);
assert.equal(reveal(100,200,600,140,30),100);
assert.equal(reveal(0,200,600,250,300),242);
assert.equal(reveal(0,200,100,50,30),0);
assert.equal(reveal(500,200,600,590,30),400);
console.log('PASS focus reveal bounds, already visible, oversized controls and content clamping');
